from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from contextlib import asynccontextmanager
from typing import List, Dict, Any
import random

from database import init_db, get_all_servers, get_server_by_id, update_server
from models import Server, ServerUpdate, EnergySavingsReport, EnergySavingsItem

@asynccontextmanager
async def lifespan(app: FastAPI):
    # Initialize SQLite database and seed 16 servers on startup
    init_db()
    yield

app = FastAPI(
    title="Data Center Digital Twin API",
    description="Real-time virtual server telemetry and energy efficiency twin layer",
    version="1.0.0",
    lifespan=lifespan
)

# Enable CORS for Vite frontend development
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

